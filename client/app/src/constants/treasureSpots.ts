/**
 * 실제 GPS fix를 무시하고 보물에 걸어서 다가가는 상황을 만드는 **접근 시뮬레이션**.
 *
 * 켜고 끄는 스위치는 여기 없다 — **심사위원용 모드가 켜져 있을 때만** 돈다
 * (store/judgeMode.ts). 모드가 꺼져 있으면 실제 좌표를 그대로 따라간다.
 * 예전에는 `TREASURE_DEV_SIMULATE_APPROACH = __DEV__ && true` 상수였는데, `__DEV__` 가드 때문에
 * 정작 이 시뮬레이션이 필요한 심사용 릴리즈 빌드에서는 켤 수 없었다.
 *
 * 아래 값들은 그 시뮬레이션이 따라가는 경로다.
 *
 * 왜 "폴백"이 아니라 "덮어쓰기"인가:
 * 예전 구현은 정해진 시간 안에 fix가 없을 때만 mock 좌표를 흘려보냈다. 그런데 실기기는 제주 밖에서도
 * fix를 곧바로 잡기 때문에 폴백이 발동하지 않고, 그러면 현재 위치가 보물에서 수백 km 떨어져 있어
 * **거리 토스트와 step1 시트를 한 번도 볼 수 없다**. 보물 마커는 서버 좌표라 지도에는 보이는데
 * 반경 UI만 안 뜨는 상태가 된다.
 *
 * 이 값이 true면 아래 거리 목록을 따라 좌표가 자동으로 가까워지므로, 반경 밖에서 접근 안내 토스트가
 * 뜨는 상태 → 반경(500m) 진입 → 토스트가 사라지고 step1 시트가 올라오는 전환을 눈으로 확인할 수 있다.
 *
 * 다가갈 대상은 이제 **서버가 내려준 실제 보물**이다 — 좌표가 진행도마다 달라지므로 목표를 상수로
 * 못 박을 수 없고, resolveApproachTarget(utils/treasureApproachSimulation.ts)이 응답을 받은 뒤에
 * 고른다. 그래서 시뮬레이션 중에도 탭 → 진행도 저장까지 실제 API로 이어진다.
 *
 * 실제 위치 기반 동작을 확인할 때는 심사위원용 모드를 끈다.
 */

/**
 * 시뮬레이션이 거쳐 가는 "가장 가까운 보물까지의 거리"(m).
 *
 * 반경(TREASURE_ENTER_RADIUS_METERS = 500) **훨씬 밖에서** 시작한다. 예전에는 600에서 시작해
 * 반경까지 한 칸(3.2초)이었는데, 그 사이에 장소명·장소 한 줄 소개를 읽을 시간이 없었고 접근
 * 안내 토스트가 시트와 겹쳐 보였다. 반경 밖 구간을 여러 칸으로 늘려 "도착하기 전"의 화면을
 * 충분히 확인할 수 있게 한다.
 *
 * 경계값(500)을 정확히 밟고 그 뒤로도 여러 단계를 두는 이유: 500m 진입에서 시트가 열리고,
 * 더 가까워져도 시트가 닫히거나 다시 열리지 않아야 한다(resolveSheetVisibility의 히스테리시스).
 */
export const TREASURE_DEV_APPROACH_DISTANCES = [1500, 1200, 900, 700, 600, 500, 400, 300, 200, 100, 30] as const;

