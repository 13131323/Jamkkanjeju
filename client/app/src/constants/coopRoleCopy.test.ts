import { describe, expect, it } from 'vitest';
import { rolePhotoGuide } from './coopRoleCopy';

/**
 * 촬영 화면 하단 안내 문구.
 *
 * 이 한 줄이 촬영 중에 역할과 대상을 알려 주는 **유일한 자리**다 — 헤더에는 뒤로가기만 있고
 * (보물찾기와 같은 형태), 카메라를 켠 뒤에는 역할 카드로 돌아갈 수 없다.
 * 그래서 "역할명이 빠지지 않는다"와 "장소가 아무리 많아도 길이가 늘어나지 않는다" 둘 다 지켜야 한다.
 */
describe('rolePhotoGuide', () => {
  it('역할명을 장소 앞에 붙인다', () => {
    expect(rolePhotoGuide('물지기', ['해변'])).toBe('물지기 · 해변');
  });

  it('장소가 많아도 두 곳까지만 잇는다', () => {
    // 역할명까지 붙은 뒤 장소가 셋 넘게 이어지면 안내가 두 줄을 넘겨 셔터를 밀어낸다
    expect(rolePhotoGuide('바람지기', ['오름', '숲길', '해안도로', '올레길'])).toBe('바람지기 · 오름 · 숲길');
  });

  it('장소를 못 받았으면 역할명만 두지 않고 할 일을 말한다', () => {
    // 서버가 locationToFind를 비워 보낼 수 있다. "물지기"만 떠 있으면 무엇을 하라는 문구인지 알 수 없다
    expect(rolePhotoGuide('물지기', [])).toBe('물지기 재료를 찾아 찍어주세요');
  });
});
