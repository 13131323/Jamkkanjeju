/**
 * "오래 걸리면 그때만 알린다" 타이머.
 *
 * 셔터를 누르고 미리보기가 뜨기까지는 촬영(takePictureAsync) → 합성 이미지 디코딩 →
 * 캡처·인코딩이 이어져서 기기에 따라 수백 ms ~ 수 초가 걸린다. 그 사이 화면은 카메라 그대로라
 * 멈춘 것처럼 보인다.
 *
 * 그렇다고 누르자마자 안내를 띄우면, 빨리 끝나는 기기에서는 떴다 사라지는 깜빡임이 된다
 * (직전 커밋 3c0b003이 정리한 방위각 깜빡임과 같은 종류의 문제다).
 * 그래서 **지연 후에만** 띄우고, 그 전에 끝나면 아예 띄우지 않는다.
 *
 * 화면에 붙은 로직이 아니라 순수 타이머로 떼어 둔 이유는 `withTimeout.ts`와 같다 —
 * "언제 뜨고 언제 안 뜨는지"가 이 기능의 전부인데, 컴포넌트 안에 두면 그걸 테스트할 수 없다.
 */

/**
 * 안내를 띄우기까지 기다리는 시간(ms).
 *
 * 이 값보다 빨리 끝나는 작업에는 아무것도 보여주지 않는다.
 *
 * 200ms으로 잡은 근거:
 * - 100ms 안쪽은 사람이 "즉시"로 느끼는 구간이라, 거기에 안내를 띄우면 정보가 아니라 깜빡임이다.
 * - 1초까지는 흐름이 끊기지 않으므로 그 전에만 알려주면 늦지 않다.
 * - 즉 100ms~1초 사이에서 고르면 되고, 깜빡임에 민감한 화면이니 그 구간의 위쪽(200ms)을 택했다.
 *   빠른 기기에서는 아무것도 안 뜨고, 느린 기기에서는 사용자가 의심을 시작하기 한참 전에 뜬다.
 */
export const PENDING_NOTICE_DELAY_MS = 200;

/**
 * `delayMs`가 지나도 취소되지 않으면 `notify`를 한 번 호출한다.
 *
 * @returns 취소 함수. 여러 번 불러도 안전하고, 이미 알린 뒤에 불러도 아무 일도 하지 않는다.
 */
export function schedulePendingNotice(notify: () => void, delayMs: number = PENDING_NOTICE_DELAY_MS): () => void {
  // 지연이 0 이하면 "지연 없이 바로"가 아니라 "쓰지 않는다"로 본다 — 깜빡임을 막는 것이 목적이므로
  // 실수로 0이 들어온 값을 즉시 표시로 해석하면 막으려던 것을 그대로 하게 된다.
  if (delayMs <= 0) return () => {};

  let timer: ReturnType<typeof setTimeout> | null = setTimeout(() => {
    timer = null;
    notify();
  }, delayMs);

  return () => {
    if (timer === null) return;
    clearTimeout(timer);
    timer = null;
  };
}
